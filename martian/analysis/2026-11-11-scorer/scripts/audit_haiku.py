"""Haiku as the reviewer, audited: audit_haiku.py   (Cal.com only; writes audit/haiku/tables.md and audit.csv)

Compares the Haiku reviewer and the Opus reviewer on the same 10 Cal.com PRs, with the auditor's verdicts on each
one's judge false positives. "Near" = same PR and file, within 10 lines.
"""
import collections, csv, glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import data
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
def verdicts(d):
    V = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'audit', d, 'outputs', 'cal.com-*.json'))):
        j = json.load(open(f))
        for a in j['audits']: V[(j['pr'], a['id'])] = a
    return V
VH, VO = verdicts('haiku'), verdicts('.')
def load(src, V):
    out = []
    for p in src.values():
        if p['row']['repo'] != 'cal.com': continue
        key = data.pr_key(p['row'])
        for it in p['items']:
            v = V.get((key, it['i']))
            out.append(dict(pr=key, it=it, verdict=v['verdict'] if v else None, dup=v.get('duplicate_of') if v else None,
                            fix=v['would_fix'] if v else None))
    return out
Hk, Op = load(data.haiku_fixed(), VH), load(data.opus(), VO)
print('item keys', sorted(Hk[0]['it'].keys()))
def cls(f):
    if f['verdict']: return f['verdict']
    return 'golden' if not f['it']['fp'] else 'unaudited'
def near(f, others):
    return any(o['pr'] == f['pr'] and o['it']['path'] == f['it']['path'] and abs((o['it']['line'] or 0) - (f['it']['line'] or 0)) <= 10 for o in others)
out = []; p = out.append
C = ['golden', 'real-defect', 'real-minor', 'wrong', 'unverifiable', 'unaudited']
p('# Haiku as the reviewer, audited on Cal.com (generated by scripts/audit_haiku.py)'); p('')
p('`golden`: the judge matched the finding to a golden (not audited). The other columns are the auditor\'s verdict on judge FP.'); p('')
p('| Reviewer | findings | ' + ' | '.join(C) + ' | serious (golden + real-defect) | share serious |'); p('|---|---|' + '---|' * (len(C) + 2))
for n, F in (('Opus 5.5 high', Op), ('Haiku 5.5 high', Hk)):
    c = collections.Counter(cls(f) for f in F); s = c['golden'] + c['real-defect']
    p('| %s | %d | %s | %d | %.0f%% |' % (n, len(F), ' | '.join(str(c[x]) for x in C), s, 100.0 * s / len(F)))
p('')
p('## Haiku judge FP by the severity Haiku gave'); p(''); p('| severity | real-defect | real-minor | wrong | unverifiable |'); p('|---|---|---|---|---|')
for sv in ['blocker', 'fix', 'consider', 'info']:
    c = collections.Counter(f['verdict'] for f in Hk if f['verdict'] and f['it']['sev'] == sv)
    p('| %s | %d | %d | %d | %d |' % (sv, c['real-defect'], c['real-minor'], c['wrong'], c['unverifiable']))
p('')
p('## Overlap of the audited real defects (not goldens)'); p('')
hd = [f for f in Hk if f['verdict'] == 'real-defect']; od = [f for f in Op if f['verdict'] == 'real-defect']
p('| | count | near a finding of the other reviewer | not near any |'); p('|---|---|---|---|')
a = sum(1 for f in hd if near(f, Op)); p('| Haiku real defects | %d | %d | %d |' % (len(hd), a, len(hd) - a))
a = sum(1 for f in od if near(f, Hk)); p('| Opus real defects | %d | %d | %d |' % (len(od), a, len(od) - a))
p('')
p('Duplicates inside the Haiku audit (duplicate_of set): %d of %d audited. would_fix on Haiku real-minor: %s.' % (
    sum(1 for f in Hk if f['dup'] is not None), len(VH), dict(collections.Counter(f['fix'] for f in Hk if f['verdict'] == 'real-minor'))))
p('')
open(os.path.join(ROOT, 'audit', 'haiku', 'tables.md'), 'w').write('\n'.join(out))
with open(os.path.join(ROOT, 'audit', 'haiku', 'audit.csv'), 'w', newline='') as fh:
    w = csv.writer(fh); w.writerow('pr id verdict dup fix conf sev topic near_opus'.split())
    for f in Hk:
        if f['verdict']:
            v = VH[(f['pr'], f['it']['i'])]
            w.writerow([f['pr'], f['it']['i'], f['verdict'], f['dup'] if f['dup'] is not None else '', f['fix'], v['confidence'], f['it']['sev'], f['it']['topic'], int(near(f, Op))])
print('\n'.join(out))
