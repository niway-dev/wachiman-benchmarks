"""Did other tools raise our audited findings: others_tables.py  (writes audit/others/tables.md)"""
import collections, csv, json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
A = {(r['pr'], r['id']): r for r in csv.DictReader(open(os.path.join(ROOT, 'audit', 'audit.csv')))}
M = {}
for rp in ('cal.com', 'sentry'):
    d = json.load(open(os.path.join(ROOT, 'audit', 'others', 'matches-%s.json' % rp)))
    for pr, rows in d.items():
        for x in rows: M[(pr, str(x['id']))] = sorted({m['tool'] for m in x['matches']})
assert set(M) == set(A), (len(M), len(A))
out = []; p = out.append
p('# Did other tools raise the same issue? (generated by scripts/others_tables.py)'); p('')
p('85 audited Opus findings the judge matched to no golden, against the comments of ten other tools on the same PR.'); p('')
p('| Auditor verdict | findings | raised by at least one other tool | by three or more | by none |'); p('|---|---|---|---|---|')
for v in ['real-defect', 'real-minor', 'wrong', 'unverifiable']:
    ks = [k for k in A if A[k]['verdict'] == v]
    p('| %s | %d | %d | %d | %d |' % (v, len(ks), sum(1 for k in ks if M[k]), sum(1 for k in ks if len(M[k]) >= 3), sum(1 for k in ks if not M[k])))
p('')
for rp in ('cal.com', 'sentry'):
    ks = [k for k in A if k[0].startswith(rp) and A[k]['verdict'] == 'real-defect']
    p('%s real defects: %d, raised by another tool: %d.' % (rp, len(ks), sum(1 for k in ks if M[k])))
p('')
p('| Tool | of our 34 real defects it also raised | of our 47 minor findings it also raised |'); p('|---|---|---|')
T = collections.Counter(); Tm = collections.Counter()
for k, ts in M.items():
    for t in ts:
        if A[k]['verdict'] == 'real-defect': T[t] += 1
        elif A[k]['verdict'] == 'real-minor': Tm[t] += 1
for t in sorted(set(T) | set(Tm), key=lambda t: -T[t]): p('| %s | %d | %d |' % (t, T[t], Tm[t]))
p('')
open(os.path.join(ROOT, 'audit', 'others', 'tables.md'), 'w').write('\n'.join(out)); print('\n'.join(out))
