"""Join the auditor's verdicts with the stored findings: audit_tables.py

Reads audit/outputs/*.json, findings-opus.csv and findings-haiku.csv. Writes audit/audit.csv and audit/tables.md.
"Serious" below means: the finding matched a golden, or the auditor called it real-defect.
"Not serious": a judge FP the auditor called real-minor, wrong or unverifiable.
"""
import collections, csv, glob, json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rd = lambda f: list(csv.DictReader(open(os.path.join(ROOT, f))))
O = {(r['pr'], r['id']): r for r in rd('findings-opus.csv')}
H = {(r['pr'], r['id']): r for r in rd('findings-haiku.csv')}
V = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'audit', 'outputs', '*.json'))):
    d = json.load(open(f))
    for a in d['audits']: V[(d['pr'], str(a['id']))] = a
repo = lambda pr: 'cal.com' if pr.startswith('cal.com') else 'sentry'
SEV = {'blocker': 3, 'fix': 2, 'consider': 1, 'info': 0}
CONF = {'high': 2, 'medium': 1, 'low': 0}

with open(os.path.join(ROOT, 'audit', 'audit.csv'), 'w', newline='') as fh:
    w = csv.writer(fh); w.writerow('pr id verdict dup fix conf sev topic kind oscore hscore echo'.split())
    for k in sorted(V):
        a, o = V[k], O[k]
        w.writerow([k[0], k[1], a['verdict'], a.get('duplicate_of') if a.get('duplicate_of') is not None else '', a['would_fix'],
                    a['confidence'], o['severity'], o['topic'], o['kind'], o['score'], H[k]['score'], o['echo']])

out = []; p = out.append
VS = ['real-defect', 'real-minor', 'wrong', 'unverifiable']
def table(title, keyfn, keys):
    p('### ' + title); p(''); p('| | ' + ' | '.join(VS) + ' | total |'); p('|---|' + '---|' * (len(VS) + 1))
    for kk in keys:
        c = collections.Counter(V[k]['verdict'] for k in V if keyfn(k) == kk)
        p('| %s | %s | %d |' % (kk, ' | '.join(str(c[v]) for v in VS), sum(c.values())))
    p('')
p('# Audit tables (generated by scripts/audit_tables.py)'); p('')
p('Audited: %d judge false positives. Verdict values: %s.' % (len(V), ', '.join(VS))); p('')
table('By repository', lambda k: repo(k[0]), ['cal.com', 'sentry'])
table('All audited, by Wachiman severity', lambda k: O[k]['severity'], ['blocker', 'fix', 'consider', 'info'])
for rp in ['cal.com', 'sentry']:
    table(rp + ', by Wachiman severity', lambda k: O[k]['severity'] if repo(k[0]) == rp else None, ['blocker', 'fix', 'consider', 'info'])
table('All audited, by Haiku echo within 10 lines', lambda k: {'1': 'echoed', '0': 'not echoed'}[O[k]['echo']], ['echoed', 'not echoed'])
table('All audited, by scorer kind (Opus scorer)', lambda k: O[k]['kind'], sorted({O[k]['kind'] for k in V}))
table('All audited, by confidence the auditor stated', lambda k: V[k]['confidence'], ['high', 'medium', 'low'])
table('All audited, by would_fix', lambda k: V[k]['would_fix'], ['yes', 'maybe', 'no'])
p('### Mean scorer score by verdict'); p(''); p('| verdict | n | Opus scorer | Haiku scorer |'); p('|---|---|---|---|')
for v in VS:
    ks = [k for k in V if V[k]['verdict'] == v]
    if ks: p('| %s | %d | %.1f | %.1f |' % (v, len(ks), sum(int(O[k]['score']) for k in ks) / len(ks), sum(int(H[k]['score']) for k in ks) / len(ks)))
p('')

# every Opus finding of the audited PRs' repositories, with a serious / not serious label
L = []
for k, o in O.items():
    if not (k[0].startswith('cal.com') or k[0].startswith('sentry')): continue
    if int(o['goldens']) > 0: L.append((k, 1))
    elif k in V: L.append((k, 1 if V[k]['verdict'] == 'real-defect' else 0))
pos = [k for k, s in L if s]; neg = [k for k, s in L if not s]
def auc(fn):
    t = sum(1.0 if fn(a) > fn(b) else 0.5 if fn(a) == fn(b) else 0.0 for a in pos for b in neg)
    return t / (len(pos) * len(neg))
sig = [('Wachiman severity', lambda k: SEV[O[k]['severity']]),
       ('Wachiman severity, then confidence', lambda k: SEV[O[k]['severity']] * 3 + CONF.get(O[k]['confidence'], 0)),
       ('Opus scorer score', lambda k: int(O[k]['score'])), ('Haiku scorer score', lambda k: int(H[k]['score'])),
       ('Haiku echo within 10 lines', lambda k: int(O[k]['echo']))]
p('## Which signal separates serious from not serious (Cal.com + Sentry, %d Opus findings)' % len(L)); p('')
p('Serious = matched a golden (%d) or audited real-defect (%d): %d. Not serious = audited real-minor, wrong or unverifiable: %d.' % (
    sum(1 for k in pos if int(O[k]['goldens']) > 0), sum(1 for k in pos if int(O[k]['goldens']) == 0), len(pos), len(neg)))
p('AUC: chance that a random serious finding ranks above a random not-serious one (0.5 = coin, 1.0 = perfect).'); p('')
p('| Signal | AUC, both | AUC, Cal.com | AUC, Sentry |'); p('|---|---|---|---|')
def auc_r(fn, rp):
    a = [k for k in pos if repo(k[0]) == rp]; b = [k for k in neg if repo(k[0]) == rp]
    return sum(1.0 if fn(x) > fn(y) else 0.5 if fn(x) == fn(y) else 0.0 for x in a for y in b) / (len(a) * len(b))
for n, fn in sig: p('| %s | %.3f | %.3f | %.3f |' % (n, auc(fn), auc_r(fn, 'cal.com'), auc_r(fn, 'sentry')))
p('')
p('### Rules for the main section (same %d findings)' % len(L)); p('')
p('| Rule: main section if | serious kept | serious sent to second section | not serious kept | not serious sent |'); p('|---|---|---|---|---|')
rules = [('everything', lambda k: True), ('severity is blocker or fix', lambda k: SEV[O[k]['severity']] >= 2),
         ('Haiku scorer gave 5 or more', lambda k: int(H[k]['score']) >= 5), ('Haiku scorer gave 6 or more', lambda k: int(H[k]['score']) >= 6),
         ('Opus scorer gave 5 or more', lambda k: int(O[k]['score']) >= 5), ('Opus scorer gave 6 or more', lambda k: int(O[k]['score']) >= 6),
         ('Haiku echoed it within 10 lines', lambda k: O[k]['echo'] == '1'),
         ('blocker or fix, or Haiku scorer gave 6 or more', lambda k: SEV[O[k]['severity']] >= 2 or int(H[k]['score']) >= 6),
         ('blocker or fix, or Haiku echoed it', lambda k: SEV[O[k]['severity']] >= 2 or O[k]['echo'] == '1')]
for n, fn in rules:
    a = sum(1 for k in pos if fn(k)); b = sum(1 for k in neg if fn(k))
    p('| %s | %d | %d | %d | %d |' % (n, a, len(pos) - a, b, len(neg) - b))
p('')
open(os.path.join(ROOT, 'audit', 'tables.md'), 'w').write('\n'.join(out))
print('\n'.join(out))
